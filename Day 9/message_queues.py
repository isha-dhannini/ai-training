#Priority Queue Broker (HEAP-based)

class PriorityBroker:
    def __init__(self):
        self.heap = []  # (priority, id, payload)

    async def publish(self, payload: dict):
        priority = payload.get("priority", 1)

        # HIGH priority should come first → use negative
        heapq.heappush(self.heap, (-priority, str(uuid.uuid4()), payload))

    async def consume(self):
        if not self.heap:
            return None

        return heapq.heappop(self.heap)[2]

    def size(self):
        return len(self.heap)

