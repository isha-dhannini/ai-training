import asyncio
import threading
import time
import random
import nest_asyncio

from prometheus_client import Gauge, start_http_server

nest_asyncio.apply()

class Broker:
    def __init__(self):
        self.queue = []
        self.dlq = []

    async def publish(self, msg: dict):
        self.queue.append(msg)

    async def consume(self):
        if not self.queue:
            return None
        return self.queue.pop(0)

broker = Broker()
print("Broker initialized")

#DLQ Metric
DLQ_DEPTH = Gauge(
    "payments_dlq_depth",
    "Number of messages in DLQ"
)

async def process(msg):
    await asyncio.sleep(0.2)

    # simulate random failure
    if random.random() < 0.4:
        raise Exception("Processing failed")

    return True


async def background_worker():
    print("🚀 Worker started...")

    while True:
        msg = await broker.consume()

        if msg is None:
            await asyncio.sleep(0.5)
            continue

        try:
            print(f"Processing {msg}")
            await process(msg)
            print("✅ Success:", msg)

        except Exception as e:
            print(" Failed → DLQ:", msg)
            broker.dlq.append(msg)

        # update Prometheus metric
        DLQ_DEPTH.set(len(broker.dlq))

start_http_server(8000)
print("Prometheus running at http://localhost:8000/metrics")

def start_worker():
    loop = asyncio.new_event_loop()
    asyncio.set_event_loop(loop)
    loop.run_until_complete(background_worker())

threading.Thread(target=start_worker, daemon=True).start()

